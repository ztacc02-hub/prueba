const $ = id => document.getElementById(id);
const video = $("video");
const channels = parseM3U(M3U);
let currentChannel = null;
let hls = null;

function parseM3U(content) {
  const lines = content.split(/\r?\n/).map(line => line.trim()).filter(Boolean);
  const result = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (!lines[i].startsWith("#EXTINF")) continue;
    const info = lines[i];
    const url = lines[i + 1];
    if (!url || url.startsWith("#")) continue;
    const attribute = name => info.match(new RegExp(`${name}="([^"]*)"`, "i"))?.[1] || "";
    const comma = info.indexOf(",");
    result.push({ name: comma >= 0 ? info.slice(comma + 1).trim() : attribute("tvg-name"), logo: attribute("tvg-logo") || FALLBACK_LOGO, url });
  }
  return result;
}

function displayName(name) {
  return name.replace(/^[^A-Za-zÀ-ÿ0-9⚽]+/, "").replace(/\s+/g, " ").trim();
}

function renderChannels(query = "") {
  const visible = channels.filter(channel => displayName(channel.name).toLocaleLowerCase().includes(query.toLocaleLowerCase()));
  $("channel-grid").replaceChildren();
  $("count").textContent = `${visible.length} CANALES`;
  if (!visible.length) {
    const empty = document.createElement("div");
    empty.className = "empty";
    empty.textContent = "No se encontraron canales.";
    $("channel-grid").appendChild(empty);
    return;
  }
  visible.forEach(channel => {
    const card = document.createElement("button");
    card.type = "button";
    card.className = "channel-card";
    card.dataset.url = channel.url;
    card.innerHTML = '<div class="channel-logo"><img alt=""></div><h3></h3><div class="card-live"><i class="live-dot"></i> EN VIVO</div>';
    const image = card.querySelector("img");
    image.src = channel.logo;
    image.onerror = () => { image.src = FALLBACK_LOGO; };
    card.querySelector("h3").textContent = displayName(channel.name);
    card.addEventListener("click", () => loadChannel(channel));
    $("channel-grid").appendChild(card);
  });
  markActiveCard();
}

function markActiveCard() {
  document.querySelectorAll(".channel-card").forEach(card => card.classList.toggle("active", card.dataset.url === currentChannel?.url));
}

function setError(message = "Prueba seleccionando otro canal o vuelve a intentarlo más tarde.") {
  $("error-detail").textContent = message;
  $("player-error").classList.add("show");
}

function clearError() { $("player-error").classList.remove("show"); }
function destroyHls() { if (hls) hls.destroy(); hls = null; }

function loadChannel(channel) {
  currentChannel = channel;
  $("current-title").textContent = displayName(channel.name);
  $("current-logo").src = channel.logo;
  $("current-logo").onerror = () => { $("current-logo").src = FALLBACK_LOGO; };
  clearError();
  markActiveCard();
  destroyHls();
  video.pause();
  video.removeAttribute("src");
  video.load();

  if (window.Hls?.isSupported()) {
    hls = new Hls({ enableWorker: true, lowLatencyMode: true, backBufferLength: 90, maxBufferLength: 30 });
    hls.loadSource(channel.url);
    hls.attachMedia(video);
    hls.on(Hls.Events.MANIFEST_PARSED, () => video.play().catch(() => {}));
    hls.on(Hls.Events.ERROR, (_, data) => {
      if (!data.fatal) return;
      if (data.type === Hls.ErrorTypes.NETWORK_ERROR) hls.startLoad();
      else if (data.type === Hls.ErrorTypes.MEDIA_ERROR) hls.recoverMediaError();
      else { destroyHls(); setError("El servidor no permite la reproducción desde este dominio o la señal está caída."); }
    });
  } else if (video.canPlayType("application/vnd.apple.mpegurl")) {
    video.src = channel.url;
    video.addEventListener("loadedmetadata", () => video.play().catch(() => {}), { once: true });
  } else setError("Este navegador no soporta reproducción HLS.");
}

